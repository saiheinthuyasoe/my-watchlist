/**
 * Refreshes src/lib/fallback-data.ts from the live AniList GraphQL API.
 * Run with: npm run refresh-fallback
 *
 * Fallback data is only used when AniList is unreachable (or during the
 * curated first paint), so it must stay small and never contain stale CDN URLs.
 */
import { writeFile } from "node:fs/promises";

const IDS = [
  151807, // Solo Leveling
  154587, // Frieren
  145064, // Jujutsu Kaisen S2
  101922, // Demon Slayer
  16498, // Attack on Titan
  21, // One Piece
  126403, // Link Click
  137667, // Lord of Mysteries
  107912, // Scissor Seven
  98861, // The King's Avatar
  136484, // Link Click S2
  156092, // The Legend of Hei (donghua)
];

const QUERY = `
  query ($ids: [Int]) {
    Page(page: 1, perPage: 50) {
      media(id_in: $ids, type: ANIME, isAdult: false) {
        id
        title { romaji english native }
        coverImage { large medium color }
        bannerImage
        description(asHtml: false)
        episodes
        duration
        status
        season
        seasonYear
        averageScore
        popularity
        genres
        tags { name category }
        type
        format
        countryOfOrigin
        isAdult
      }
    }
  }
`;

function cleanDescription(value) {
  if (!value) return null;
  return value
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]*>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
    .slice(0, 900);
}

function toMedia(media) {
  return {
    id: media.id,
    title: {
      romaji: media.title.romaji,
      english: media.title.english ?? null,
      native: media.title.native,
    },
    coverImage: {
      large: media.coverImage.large,
      medium: media.coverImage.medium,
      color: media.coverImage.color ?? null,
    },
    bannerImage: media.bannerImage ?? null,
    description: cleanDescription(media.description),
    episodes: media.episodes ?? null,
    duration: media.duration ?? null,
    status: media.status,
    season: media.season ?? null,
    seasonYear: media.seasonYear ?? null,
    averageScore: media.averageScore ?? null,
    popularity: media.popularity ?? 0,
    genres: media.genres ?? [],
    tags: (media.tags ?? []).slice(0, 8),
    type: media.type,
    format: media.format ?? null,
    countryOfOrigin: media.countryOfOrigin ?? null,
    isAdult: media.isAdult ?? false,
  };
}

const response = await fetch("https://graphql.anilist.co", {
  method: "POST",
  headers: { "Content-Type": "application/json", Accept: "application/json" },
  body: JSON.stringify({ query: QUERY, variables: { ids: IDS } }),
});

if (!response.ok) {
  throw new Error(`AniList responded with ${response.status}`);
}

const payload = await response.json();
if (payload.errors?.length) {
  throw new Error(payload.errors[0]?.message ?? "AniList query failed");
}

const byId = new Map(payload.data.Page.media.map((media) => [media.id, media]));
const ordered = IDS.map((id) => byId.get(id)).filter(Boolean);
const missing = IDS.filter((id) => !byId.has(id));
if (missing.length) {
  console.warn(`Warning: AniList returned no data for ids: ${missing.join(", ")}`);
}

const anime = ordered.filter((media) => media.countryOfOrigin !== "CN");
const donghua = ordered.filter((media) => media.countryOfOrigin === "CN");

if (anime.length === 0 || donghua.length === 0) {
  throw new Error("Curated lists would be empty — aborting to avoid wiping fallback data.");
}

const header = `import type { AniListMedia } from "@/types/anime";

/**
 * Curated offline fallback used when the AniList API is unreachable.
 * Generated by scripts/refresh-fallback.mjs — do not edit by hand.
 * Last refreshed: ${new Date().toISOString().slice(0, 10)}
 */
`;

const body = `${header}
export const FALLBACK_ANIME: AniListMedia[] = ${JSON.stringify(
  anime.map(toMedia),
  null,
  2
)};

export const FALLBACK_DONGHUA: AniListMedia[] = ${JSON.stringify(
  donghua.map(toMedia),
  null,
  2
)};
`;

await writeFile("src/lib/fallback-data.ts", body, "utf8");
console.log(
  `Wrote ${anime.length} anime and ${donghua.length} donghua titles to src/lib/fallback-data.ts`
);
